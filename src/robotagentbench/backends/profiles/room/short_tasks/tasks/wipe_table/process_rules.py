"""Eight-point score candidate using unchanged, trusted source measurements.

No scene/physics writes, native registration, action policy or new thresholds.
The source wipe scorer owns physical grasp/lift, clean/return and brush-drop
semantics. The existing interaction scorer owns approach/contact detection.
Only this candidate's approved reward weights differ from those sources.
"""
from copy import deepcopy
import math

from openend.tasks.wipe_table.process_rules import ProcessScorer, StepFacts
from short_tasks.tasks.interaction_progress_v1.scoring import (
    APPROACH_POINTS, APPROACH_TIERS, TOUCH_POINTS, Progress, Sample,
)

REVISION = "short-wipe-1-1-1-5-v1"
BRUSH = "/World/OpenEndWipe/Brush"
MAXIMUM = 8.0
APPROACH_MAXIMUM = 1.0
TOUCH_MAXIMUM = 1.0
LIFT_MAXIMUM = 1.0
WIPE_MAXIMUM = 5.0


class ShortWipeScorer:
    """Episode-local rule component, not an admitted physical runtime.

`facts` must be generated by the original brush-only PhysX adapter, after its
native grasp gate filters stain updates. `interaction` must be the existing
measured collision-surface distance/contact sample for this exact brush.
Synthetic caller-provided evidence is useful only for unit tests.
"""

    def __init__(self, episode_id, physics_dt_s, start_xy, start_yaw_rad):
        self._wipe = ProcessScorer(
            episode_id, physics_dt_s, start_xy, start_yaw_rad)
        self._interaction = Progress(episode_id, (BRUSH,))
        if APPROACH_POINTS <= 0 or TOUCH_POINTS != TOUCH_MAXIMUM:
            raise ValueError("Unexpected existing interaction score contract")
        self.episode_id = episode_id

    @property
    def ended(self):
        return self._wipe.ended

    @property
    def reason(self):
        return self._wipe.reason

    def configure_clock(self, dt):
        self._wipe.configure_clock(dt)

    def pause(self):
        self._wipe.pause()

    def suspend_substep(self, now, dt):
        self._wipe.suspend_substep(now, dt)

    def observe_step(self, facts, interaction, control_step, *, rebase=False):
        if not isinstance(facts, StepFacts) or not facts.frames:
            raise ValueError("Current physical wipe facts required")
        if not isinstance(interaction, Sample) or interaction.active is not True:
            raise ValueError("One active, measured brush interaction required")
        # Validate both evidence channels transactionally: bad interaction
        # samples cannot consume a wipe event or vice versa.
        wipe, progress = deepcopy(self._wipe), deepcopy(self._interaction)
        baseline = progress.last is None
        if baseline and (facts.coverage != facts.initial_coverage or any(
                f.tool_held or f.tool_robot_contact for f in facts.frames)):
            raise ValueError("Initial brush must be untouched, unheld and dirty")
        wipe.observe_step(facts)
        progress.observe(self.episode_id, control_step, facts.frames[-1].time_s,
                         {BRUSH: interaction}, baseline=baseline or rebase)
        self._wipe, self._interaction = wipe, progress
        return self.summary()

    def summary(self):
        source = self._wipe.summary()
        interaction = self._interaction.summary()
        item = interaction["items"][0]
        approach = item["approach"] * APPROACH_MAXIMUM / APPROACH_POINTS
        touch = item["touch"]
        lift = LIFT_MAXIMUM if source["stages"]["grasp"] else 0.0
        # Reuse the source's absolute high-watermark progress, not a sum of
        # frame reductions. The source clean threshold remains unchanged.
        wipe = source["wipe_points"] * WIPE_MAXIMUM / source["maximum_wipe_points"]
        earned = approach + touch + lift + wipe
        deductions = source["deducted_points"]
        if not math.isfinite(earned) or earned > MAXIMUM + 1e-9:
            raise ValueError("Invalid task reward total")
        stages = dict(approach=approach, contact=touch, grasp_lift=lift,
                      wipe_progress=wipe)
        return dict(
            schema="arena.short_wipe.score.v1", revision=REVISION,
            episode_id=self.episode_id, score=max(0.0, earned-deductions),
            earned_points=earned, deducted_points=deductions,
            maximum_score=MAXIMUM, stage_points=stages,
            stage_maxima=dict(approach=1.0, contact=1.0, grasp_lift=1.0,
                              wipe_progress=5.0),
            approach_tiers=[dict(distance_m=d, points=p/APPROACH_POINTS)
                            for d, p in APPROACH_TIERS],
            skipped_initial_tiers=item["skipped_approach_thresholds_m"],
            started=source["started"], coverage=source["coverage"],
            initial_coverage=source["initial_coverage"],
            # No new success predicate: keep source clean + returned/released
            # stability. Returning remains a condition, but adds zero points.
            success=source["success"], reason=source["reason"],
            failure=source["failure"], finalized=source["finalized"],
            deductions=source["deductions"], returned_now=source["returned_now"],
            events=self._events(source, interaction),
            public_runtime_id="wipe_table",
            evidence_status="rule_component_not_native_validation")

    def _events(self, source, interaction):
        out = []
        for event in interaction["events"]:
            row = deepcopy(event)
            if row["kind"] == "approach":
                row["points"] *= APPROACH_MAXIMUM / APPROACH_POINTS
            out.append(row)
        for event in source["events"] if "events" in source else self._wipe.events:
            row = deepcopy(event)
            if row["kind"] == "wipe_progress":
                row["points"] *= WIPE_MAXIMUM / source["maximum_wipe_points"]
            elif row["kind"] == "tool_returned":
                row["points"] = 0
            out.append(row)
        return sorted(out, key=lambda row: row["time_s"])

    def finalize(self, reason):
        self._wipe.finalize(reason)
        return self.summary()
