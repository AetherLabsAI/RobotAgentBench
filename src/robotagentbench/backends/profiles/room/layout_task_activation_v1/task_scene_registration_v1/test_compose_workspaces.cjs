const assert=require('node:assert/strict');
const {build}=require('./compose_workspaces.cjs');
const request=require('./four_workspaces_request.json');
const plan=build(request);
assert.equal(plan.parts.length,4);assert.equal(plan.placed_part_count,4);
assert.equal(plan.status,'workspace_plan_ready');
assert.equal(plan.runtime_registered,false);assert.equal(plan.assets_instantiated,false);
assert.equal(plan.usd_written,false);assert.equal(plan.physics_validated,false);
assert.equal(plan.scene_generation_allowed,false);
assert.deepEqual(plan.parts.map(p=>p.part_id),request.task_types);
assert.deepEqual(plan,build({...request,task_types:[...request.task_types].reverse()}));
const subset=build({...request,task_types:['coffee','tray']});
assert.deepEqual(subset.parts.map(p=>p.part_id),['coffee','tray']);
for(const p of subset.parts)assert.equal(p.initialization_status,'not_instantiated');
assert.throws(()=>build({...request,task_types:['coffee','coffee']}));
assert.throws(()=>build({...request,task_types:['unknown']}));
assert.throws(()=>build({...request,layout_id:999}));
assert.throws(()=>build({...request,seed:0}));
assert.throws(()=>build({...request,physics_hz:60}));
console.log(JSON.stringify({tests:'passed',parts:plan.parts.map(p=>({id:p.part_id,support:p.placement.group})),subset:subset.parts.map(p=>p.part_id),runtime_registered:false}));
